func TestAllAgentEventTypes(t *testing.T) {
	types := AllAgentEventTypes()
	if len(types) != 10 {
		t.Errorf("expected 10 event types, got %d", len(types))
	}

	// Verify each type has two parts (suffix.event)
	for _, et := range types {
		parts := splitAt(et, ".")
		if len(parts) < 2 {
			t.Errorf("event type %q doesn't have namespace separator", et)
		}
	}
}

// Helper to avoid importing strings just for the test.
func splitAt(s, sep string) []string {
	for i := 0; i < len(s)-len(sep)+1; i++ {
		if s[i:i+len(sep)] == sep {
			return []string{s[:i], s[i+len(sep):]}
		}
	}
	return []string{s}
}
