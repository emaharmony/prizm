package agentns

import "testing"

func TestNamespaceEventType(t *testing.T) {
	ns := New("lumi")
	tests := []struct {
		suffix string
		want   string
	}{
		{"agent.started", "lumi.agent.started"},
		{"tool.completed", "lumi.tool.completed"},
		{"llm.requested", "lumi.llm.requested"},
		{"channel.sent", "lumi.channel.sent"},
	}

	for _, tt := range tests {
		got := ns.EventType(tt.suffix)
		if got != tt.want {
			t.Errorf("EventType(%q) = %q, want %q", tt.suffix, got, tt.want)
		}
	}
}

